export const LANGUAGES = Object.keys(STRINGS);
let lang = "en";

export function language() {
  return lang;
}

/// The language to start with: the saved one, else the system's, else English.
export function pickLanguage(saved) {
  if (saved && STRINGS[saved]) return saved;
  const sys = (navigator.language || "en").slice(0, 2).toLowerCase();
  return STRINGS[sys] ? sys : "en";
}

export function setLanguage(l) {
  lang = STRINGS[l] ? l : "en";
  document.documentElement.lang = lang;
  apply(document);
}

export function t(key, vars) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/// Fills data-i18n texts and data-i18n-attr attributes under root.
export function apply(root) {
  for (const el of root.querySelectorAll("[data-i18n]")) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of root.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of el.dataset.i18nAttr.split(",")) {
      const [attr, key] = pair.split(":");
      el.setAttribute(attr.trim(), t(key.trim()));
    }
  }
}

export function formatSize(n) {
  if (n < 1024) return t("size.b", { n });
  if (n < 1024 * 1024) return t("size.kb", { n: (n / 1024).toFixed(n < 10240 ? 1 : 0) });
  return t("size.mb", { n: (n / 1024 / 1024).toFixed(1) });
}

export function formatDuration(ms) {
  if (ms < 1000) return t("time.ms", { n: ms });
  return t("time.s", { n: (ms / 1000).toFixed(ms < 10000 ? 2 : 1) });
}

export function formatTime(ms) {
  return new Date(ms).toLocaleString(lang, { dateStyle: "short", timeStyle: "medium" });
}

/// A moment in a list: the time alone today, the day and month (no year) and the time before.
export function formatWhen(ms) {
  const d = new Date(ms);
  const today = d.toDateString() === new Date().toDateString();
  return today
    ? d.toLocaleTimeString(lang, { timeStyle: "medium" })
    : d.toLocaleString(lang, { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" });
}
